import React, { useState } from "react";
import FormWrapper from "./FormWrapper";
import GreenTickBox from "../components/GreenTickBox";
import { generateFeasibilityReportPDF } from "../utils/pdfGenerators";

const CATEGORY_OPTIONS = [
  "-- Select Category of Change --",
  "Manufacturing Process / Product Requirement",
  "System Requirement",
  "Inspection Requirement",
  "Tooling / Pattern / Fixture Modification",
  "Machine / CNC Program Revision",
  "Any Other Requirement",
];

const FeasibilityReport = () => {
  const [formData, setFormData] = useState({
    slNo: "",
    date: new Date().toISOString().split("T")[0],
    from: "Dept Owner",
    to: "CFT",
    partName: "",
    partNo: "",
    customer: "",
    categoryOfChange: "",
    // Category of Change rows
    manufacturingProcess: { requirements: "", feasible: "" },
    systemRequirement: { requirements: "", feasible: "" },
    inspectionRequirement: { requirements: "", feasible: "" },
    anyOtherRequirement: { requirements: "", feasible: "" },
    // Additional Manufacturing
    additionalManufacturing: "",
    // Conclusion
    conclusionFeasible: true,
    conclusionNotFeasible: false,
    // CFT Members Sign / Date (6 slots)
    cftMembers: ["", "", "", "", "", ""],
    // Comments & Forwarded
    comments: "",
    forwardedTo: "",
  });

  const [toastMsg, setToastMsg] = useState("");
  const [isDownloadingPdf, setIsDownloadingPdf] = useState(false);

  const updateField = (field, value) => setFormData({ ...formData, [field]: value });

  const updateCategoryRow = (category, subField, value) => {
    setFormData({
      ...formData,
      [category]: { ...formData[category], [subField]: value },
    });
  };

  const updateCftMember = (index, value) => {
    const updated = [...formData.cftMembers];
    updated[index] = value;
    setFormData({ ...formData, cftMembers: updated });
  };

  const handleSave = async () => {
    localStorage.setItem("sakthi_feasibility_report", JSON.stringify(formData));

    const apiUrl = process.env.REACT_APP_API_URL || "http://localhost:5000";
    const token = localStorage.getItem("token");

    try {
      const response = await fetch(`${apiUrl}/api/forms/feasibility-report`, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: token ? `Bearer ${token}` : "",
        },
        body: JSON.stringify({
          recordKey: formData.slNo || `SL-${Date.now()}`,
          partName: formData.partName,
          customer: formData.customer,
          status: formData.conclusionFeasible ? "Approved" : "Pending",
          formData,
        }),
      });

      if (!response.ok) {
        const errorData = await response.json();
        throw new Error(errorData.error || "Server save failed");
      }

      setToastMsg("Feasibility Report saved successfully to database!");
    } catch (err) {
      setToastMsg("Saved locally in browser storage (Backend server offline).");
    }

    setTimeout(() => setToastMsg(""), 3500);
  };

  const handlePrint = async () => {
    setIsDownloadingPdf(true);
    const apiUrl = process.env.REACT_APP_API_URL || "http://localhost:5000";
    const slNo = formData.slNo || "FR-2026-001";

    try {
      const token = localStorage.getItem("token");
      const res = await fetch(`${apiUrl}/api/feasibility-report/report?slNo=${encodeURIComponent(slNo)}`, {
        method: "GET",
        headers: token ? { Authorization: `Bearer ${token}` } : {},
      });

      if (res.ok) {
        const blob = await res.blob();
        const downloadUrl = window.URL.createObjectURL(blob);
        const link = document.createElement("a");
        link.href = downloadUrl;
        link.download = `FeasibilityReport_${slNo}.pdf`;
        document.body.appendChild(link);
        link.click();
        document.body.removeChild(link);
        window.URL.revokeObjectURL(downloadUrl);
        setToastMsg("Official PDF generated by Backend Controller & downloaded!");
        setTimeout(() => setToastMsg(""), 3500);
        return;
      }
      throw new Error("Backend stream responded with status " + res.status);
    } catch (backendErr) {
      generateFeasibilityReportPDF(formData);
      setToastMsg("Official PDF generated and downloaded successfully!");
      setTimeout(() => setToastMsg(""), 3500);
    } finally {
      setIsDownloadingPdf(false);
    }
  };

  return (
    <FormWrapper
      title="FEASIBILITY REPORT FOR CHANGE REQUEST"
      qfNo="QF / 07 / MRO – 02"
      revDate="10 / 06 / 2015"
      onSave={handleSave}
      onPrint={handlePrint}
      isDownloadingPdf={isDownloadingPdf}
    >
      {toastMsg && (
        <div className="mb-3 p-3 bg-green-100 border border-green-500 text-green-800 rounded text-xs font-bold print:hidden">
          {toastMsg}
        </div>
      )}

      {/* ROW 1: SL. No & Date + Pen note "next 2) timing plan" */}
      <div className="grid grid-cols-12 border-b-[1.5px] border-black text-xs">
        <div className="col-span-12 sm:col-span-6 border-b-[1.5px] sm:border-b-0 sm:border-r-[1.5px] border-black px-2 py-1.5 flex items-center">
          <span className="font-bold uppercase text-[10px] whitespace-nowrap mr-1">SL. No (of Change Request) :</span>
          <input
            type="text"
            value={formData.slNo}
            onChange={(e) => updateField("slNo", e.target.value)}
            className="w-full font-bold outline-none bg-transparent"
          />
        </div>
        <div className="col-span-12 sm:col-span-6 px-2 py-1.5 flex items-center justify-between">
          <div className="flex items-center flex-1">
            <span className="font-bold uppercase text-[10px] whitespace-nowrap mr-1">Date :</span>
            <input
              type="date"
              value={formData.date}
              onChange={(e) => updateField("date", e.target.value)}
              className="w-full font-bold outline-none bg-transparent text-[10px]"
            />
          </div>
          <span className="text-[9px] font-mono font-bold text-gray-500 print:hidden ml-2">
            next → 2) Timing Plan
          </span>
        </div>
      </div>

      {/* ROW 2: FROM | TO */}
      <div className="grid grid-cols-12 border-b-[1.5px] border-black text-xs">
        <div className="col-span-12 sm:col-span-6 border-b-[1.5px] sm:border-b-0 sm:border-r-[1.5px] border-black px-2 py-1.5 flex items-center">
          <span className="font-bold uppercase text-[10px] whitespace-nowrap mr-1">FROM :</span>
          <input
            type="text"
            value={formData.from}
            onChange={(e) => updateField("from", e.target.value)}
            className="w-full font-bold outline-none bg-transparent"
          />
        </div>
        <div className="col-span-12 sm:col-span-6 px-2 py-1.5 flex items-center">
          <span className="font-bold uppercase text-[10px] whitespace-nowrap mr-1">TO :</span>
          <input
            type="text"
            value={formData.to}
            onChange={(e) => updateField("to", e.target.value)}
            className="w-full font-bold outline-none bg-transparent"
          />
        </div>
      </div>

      {/* ROW 3: Part Name */}
      <div className="border-b-[1.5px] border-black px-2 py-1.5 flex items-center text-xs">
        <span className="font-bold uppercase text-[10px] whitespace-nowrap mr-1">Part Name :-</span>
        <input
          type="text"
          value={formData.partName}
          onChange={(e) => updateField("partName", e.target.value)}
          className="w-full font-bold outline-none bg-transparent"
        />
      </div>

      {/* ROW 4: Part No */}
      <div className="border-b-[1.5px] border-black px-2 py-1.5 flex items-center text-xs">
        <span className="font-bold uppercase text-[10px] whitespace-nowrap mr-1">Part No :-</span>
        <input
          type="text"
          value={formData.partNo}
          onChange={(e) => updateField("partNo", e.target.value)}
          className="w-full font-bold outline-none bg-transparent"
        />
      </div>

      {/* ROW 5: Customer */}
      <div className="border-b-[1.5px] border-black px-2 py-1.5 flex items-center text-xs">
        <span className="font-bold uppercase text-[10px] whitespace-nowrap mr-1">Customer :-</span>
        <input
          type="text"
          value={formData.customer}
          onChange={(e) => updateField("customer", e.target.value)}
          className="w-full font-bold outline-none bg-transparent"
        />
      </div>

      {/* ROW 6: CATEGORY OF CHANGE with Dropdown */}
      <div className="border-b-[1.5px] border-black px-2 py-1.5 bg-gray-50 flex flex-col sm:flex-row sm:items-center justify-between gap-2 text-xs">
        <div>
          <span className="font-black uppercase text-[10px] tracking-wider text-black">
            CATEGORY OF CHANGE
          </span>
          <span className="text-[9px] text-gray-600 block">(as per the change request)</span>
        </div>
        <div className="flex items-center gap-2">
          <select
            value={formData.categoryOfChange}
            onChange={(e) => updateField("categoryOfChange", e.target.value)}
            className="text-xs p-1 bg-white border border-gray-400 rounded font-bold"
          >
            {CATEGORY_OPTIONS.map((c) => (
              <option key={c} value={c}>
                {c}
              </option>
            ))}
          </select>
        </div>
      </div>

      {/* Requirements Table Header */}
      <div className="grid grid-cols-12 border-b-[1.5px] border-black bg-gray-100 font-black text-[10px] uppercase text-black text-center">
        <div className="col-span-4 border-r-[1.5px] border-black p-2 text-left">
          Category / Item
        </div>
        <div className="col-span-5 border-r-[1.5px] border-black p-2">
          REQUIREMENTS OF THE CHANGE
        </div>
        <div className="col-span-3 p-2">
          FEASIBLE / NOT FEASIBLE
        </div>
      </div>

      {/* Category Rows */}
      {[
        { key: "manufacturingProcess", label: "Manufacturing Process / Product Requirement" },
        { key: "systemRequirement", label: "System Requirement" },
        { key: "inspectionRequirement", label: "Inspection Requirement" },
        { key: "anyOtherRequirement", label: "Any Other Requirement" },
      ].map((row) => (
        <div key={row.key} className="grid grid-cols-12 border-b-[1.5px] border-black min-h-[55px] text-xs">
          <div className="col-span-4 border-r-[1.5px] border-black p-2 flex items-start font-bold text-[10px] bg-white">
            {row.label}
          </div>
          <div className="col-span-5 border-r-[1.5px] border-black p-1 bg-white">
            <textarea
              rows="2"
              value={formData[row.key].requirements}
              onChange={(e) => updateCategoryRow(row.key, "requirements", e.target.value)}
              className="w-full text-xs outline-none resize-none bg-transparent p-1"
              placeholder="Specify requirements..."
            />
          </div>
          <div className="col-span-3 p-1 bg-white">
            <textarea
              rows="2"
              value={formData[row.key].feasible}
              onChange={(e) => updateCategoryRow(row.key, "feasible", e.target.value)}
              className="w-full text-xs outline-none resize-none bg-transparent p-1 font-bold text-center"
              placeholder="Feasible / Not Feasible..."
            />
          </div>
        </div>
      ))}

      {/* Additional Resource Section */}
      <div className="border-b-[1.5px] border-black text-xs">
        <div className="px-2 py-1.5 border-b border-gray-300 bg-gray-50 font-bold text-[10px] text-black uppercase">
          Additional Manufacturing or Inspection or other Resource requirement at Foundry / Machine Shop
        </div>
        <div className="p-2 min-h-[60px]">
          <textarea
            rows="3"
            value={formData.additionalManufacturing}
            onChange={(e) => updateField("additionalManufacturing", e.target.value)}
            className="w-full text-xs outline-none resize-none bg-transparent"
            placeholder="Details of machine capacity, tooling investments, gauges, personnel..."
          />
        </div>
      </div>

      {/* CONCLUSION Row */}
      <div className="grid grid-cols-12 border-b-[1.5px] border-black min-h-[46px] text-xs">
        <div className="col-span-4 border-r-[1.5px] border-black p-2 flex items-center font-black uppercase text-[10px] tracking-wider">
          CONCLUSION :
        </div>
        <div className="col-span-8 p-2 flex items-center gap-8">
          <GreenTickBox
            id="fr_feasible"
            label="FEASIBLE"
            checked={formData.conclusionFeasible}
            onChange={(e) =>
              setFormData({ ...formData, conclusionFeasible: e.target.checked, conclusionNotFeasible: false })
            }
          />
          <GreenTickBox
            id="fr_not_feasible"
            label="NOT FEASIBLE"
            checked={formData.conclusionNotFeasible}
            onChange={(e) =>
              setFormData({ ...formData, conclusionNotFeasible: e.target.checked, conclusionFeasible: false })
            }
          />
        </div>
      </div>

      {/* CFT MEMBERS SIGN / DATE (1 to 6) – uniform physical signing spaces */}
      <div className="grid grid-cols-12 border-b-[1.5px] border-black text-xs">
        <div className="col-span-12 sm:col-span-3 border-b-[1.5px] sm:border-b-0 sm:border-r-[1.5px] border-black p-3 flex flex-col justify-center bg-gray-50/50">
          <span className="font-black uppercase text-[10px] tracking-wider leading-tight">CFT MEMBERS SIGN / DATE</span>
          <span className="text-[9px] text-gray-500 font-mono mt-1">Team Participation</span>
          <span className="text-[8px] text-gray-400 mt-0.5 print:hidden">6 Cross-Functional Approver Slots</span>
        </div>
        <div className="col-span-12 sm:col-span-9 grid grid-cols-1 sm:grid-cols-2 divide-y sm:divide-y-0 sm:divide-x-[1.5px] divide-black">
          <div className="flex flex-col divide-y divide-black">
            {[0, 1, 2].map((i) => (
              <div key={i} className="p-2 min-h-[48px] flex flex-col justify-between bg-white">
                <div className="flex items-center justify-between">
                  <span className="font-bold text-[10px] text-gray-800">Member {i + 1}</span>
                  <span className="text-[8px] font-mono text-gray-400">CFT</span>
                </div>
                <div className="flex items-center gap-2 mt-1">
                  <input
                    type="text"
                    placeholder="Sign: __________________________"
                    value={formData.cftMembers[i]}
                    onChange={(e) => updateCftMember(i, e.target.value)}
                    className="w-full text-xs font-bold border-b border-gray-400 focus:border-black outline-none bg-transparent pb-0.5"
                  />
                </div>
              </div>
            ))}
          </div>
          <div className="flex flex-col divide-y divide-black">
            {[3, 4, 5].map((i) => (
              <div key={i} className="p-2 min-h-[48px] flex flex-col justify-between bg-white">
                <div className="flex items-center justify-between">
                  <span className="font-bold text-[10px] text-gray-800">Member {i + 1}</span>
                  <span className="text-[8px] font-mono text-gray-400">CFT</span>
                </div>
                <div className="flex items-center gap-2 mt-1">
                  <input
                    type="text"
                    placeholder="Sign: __________________________"
                    value={formData.cftMembers[i]}
                    onChange={(e) => updateCftMember(i, e.target.value)}
                    className="w-full text-xs font-bold border-b border-gray-400 focus:border-black outline-none bg-transparent pb-0.5"
                  />
                </div>
              </div>
            ))}
          </div>
        </div>
      </div>

      {/* COMMENTS & FORWARDED TO – generous signing and acknowledgement space */}
      <div className="grid grid-cols-12 text-xs min-h-[56px]">
        <div className="col-span-12 sm:col-span-6 border-b-[1.5px] sm:border-b-0 sm:border-r-[1.5px] border-black p-2.5 flex flex-col justify-between">
          <span className="font-black uppercase text-[10px] whitespace-nowrap mb-1">COMMENTS :-</span>
          <input
            type="text"
            placeholder="Official comments / action plan..."
            value={formData.comments}
            onChange={(e) => updateField("comments", e.target.value)}
            className="w-full text-xs outline-none border-b border-gray-400 focus:border-black bg-transparent font-bold pb-0.5"
          />
        </div>
        <div className="col-span-12 sm:col-span-6 p-2.5 flex flex-col justify-between">
          <div className="flex items-center justify-between mb-1">
            <span className="font-black uppercase text-[10px] whitespace-nowrap">FORWARDED TO :</span>
            <span className="text-[9px] font-mono text-gray-500 font-bold print:hidden">
              (acknowledgement)
            </span>
          </div>
          <input
            type="text"
            placeholder="Recipient Dept / Authority Sign: ____________________"
            value={formData.forwardedTo}
            onChange={(e) => updateField("forwardedTo", e.target.value)}
            className="w-full text-xs outline-none border-b border-gray-400 focus:border-black bg-transparent font-bold pb-0.5"
          />
        </div>
      </div>

      {/* Footer line */}
      <div className="flex justify-between items-center text-[10px] font-bold text-gray-800 p-1 border-t-[1.5px] border-black font-mono">
        <span>QF / 07 / MRO – 02</span>
        <span>10 / 06 / 2015</span>
      </div>
    </FormWrapper>
  );
};

export default FeasibilityReport;
